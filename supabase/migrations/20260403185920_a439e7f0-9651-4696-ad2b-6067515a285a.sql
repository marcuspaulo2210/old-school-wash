-- Profiles
CREATE POLICY "Authenticated view profiles" ON profiles FOR SELECT TO authenticated USING (true);
CREATE POLICY "Users insert own profile" ON profiles FOR INSERT TO authenticated WITH CHECK (auth.uid() = id);
CREATE POLICY "Users update own profile" ON profiles FOR UPDATE TO authenticated USING (auth.uid() = id);
CREATE POLICY "Admins update any profile" ON profiles FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'admin'));

-- User roles
CREATE POLICY "View own roles" ON user_roles FOR SELECT TO authenticated USING (auth.uid() = user_id);
CREATE POLICY "Admins view all roles" ON user_roles FOR SELECT TO authenticated USING (has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins insert roles" ON user_roles FOR INSERT TO authenticated WITH CHECK (has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins update roles" ON user_roles FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'admin'));
CREATE POLICY "Admins delete roles" ON user_roles FOR DELETE TO authenticated USING (has_role(auth.uid(), 'admin'));

-- Clothing types
CREATE POLICY "View clothing types" ON clothing_types FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin insert clothing types" ON clothing_types FOR INSERT TO authenticated WITH CHECK (has_role(auth.uid(), 'admin'));
CREATE POLICY "Admin update clothing types" ON clothing_types FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'admin'));
CREATE POLICY "Admin delete clothing types" ON clothing_types FOR DELETE TO authenticated USING (has_role(auth.uid(), 'admin'));

-- Orders
CREATE POLICY "Client view own orders" ON orders FOR SELECT TO authenticated USING (client_id = auth.uid());
CREATE POLICY "Admin view all orders" ON orders FOR SELECT TO authenticated USING (has_role(auth.uid(), 'admin'));
CREATE POLICY "Driver view assigned orders" ON orders FOR SELECT TO authenticated USING (driver_id = auth.uid());
CREATE POLICY "Production view orders" ON orders FOR SELECT TO authenticated USING (has_role(auth.uid(), 'producao'));
CREATE POLICY "Client create orders" ON orders FOR INSERT TO authenticated WITH CHECK (client_id = auth.uid());
CREATE POLICY "Admin create orders" ON orders FOR INSERT TO authenticated WITH CHECK (has_role(auth.uid(), 'admin'));
CREATE POLICY "Admin update orders" ON orders FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'admin'));
CREATE POLICY "Driver update assigned" ON orders FOR UPDATE TO authenticated USING (driver_id = auth.uid());
CREATE POLICY "Production update orders" ON orders FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'producao'));
CREATE POLICY "Admin delete orders" ON orders FOR DELETE TO authenticated USING (has_role(auth.uid(), 'admin'));

-- Order items
CREATE POLICY "View accessible items" ON order_items FOR SELECT TO authenticated USING (
  EXISTS (SELECT 1 FROM orders WHERE orders.id = order_items.order_id AND (
    orders.client_id = auth.uid() OR orders.driver_id = auth.uid() OR
    has_role(auth.uid(), 'admin') OR has_role(auth.uid(), 'producao')))
);
CREATE POLICY "Client insert items" ON order_items FOR INSERT TO authenticated WITH CHECK (
  EXISTS (SELECT 1 FROM orders WHERE orders.id = order_items.order_id AND orders.client_id = auth.uid())
);
CREATE POLICY "Admin insert items" ON order_items FOR INSERT TO authenticated WITH CHECK (has_role(auth.uid(), 'admin'));
CREATE POLICY "Production update items" ON order_items FOR UPDATE TO authenticated USING (
  EXISTS (SELECT 1 FROM orders WHERE orders.id = order_items.order_id) AND has_role(auth.uid(), 'producao')
);
CREATE POLICY "Admin update items" ON order_items FOR UPDATE TO authenticated USING (has_role(auth.uid(), 'admin'));
CREATE POLICY "Admin delete items" ON order_items FOR DELETE TO authenticated USING (has_role(auth.uid(), 'admin'));
